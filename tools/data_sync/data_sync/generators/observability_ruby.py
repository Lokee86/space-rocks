"""Ruby generator for the observability source-of-truth contract."""

from __future__ import annotations

import json
import re

from data_sync.model.observability import ObservabilityContract


def _quote(value: object) -> str:
    """Return a safely quoted Ruby string literal."""
    return json.dumps(str(value), ensure_ascii=False)


def _literal(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "nil"
    if isinstance(value, str):
        return _quote(value)
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_literal(item) for item in value) + "]"
    if isinstance(value, dict):
        entries = [
            f"{_literal(key)} => {_literal(item)}"
            for key, item in value.items()
        ]
        return "{" + ", ".join(entries) + "}"
    raise TypeError(f"unsupported Ruby literal: {type(value).__name__}")


def _constant_name(value: str) -> str:
    words = [word for word in re.split(r"[^A-Za-z0-9]+", value) if word]
    name = "_".join(word.upper() for word in words) or "GENERATED"
    if name[0].isdigit():
        name = "VALUE_" + name
    return name


def _constant(prefix: str, value: str) -> str:
    return f"{prefix}_{_constant_name(value)}"


def _frozen_literal(value: object) -> str:
    literal = _literal(value)
    if isinstance(value, (list, tuple, dict)):
        return f"{literal}.freeze"
    return literal


def generate_observability_ruby(contract: ObservabilityContract) -> str:
    """Return deterministic, self-contained Ruby for an observability contract."""
    schema = contract.schema
    envelope = schema.envelope
    limits = schema.limits
    free_form = schema.free_form_fields
    fields = sorted(contract.fields, key=lambda item: item.name)
    events = sorted(contract.events, key=lambda item: item.name)
    services = sorted(contract.services, key=lambda item: item.key)
    tiers = sorted(contract.retention_tiers, key=lambda item: item.name)
    redaction = contract.redaction

    lines = [
        "# Code generated by tools/data_sync; DO NOT EDIT.",
        "",
        "module Observability",
        "  module ContractGenerated",
        "    SCHEMA_VERSION = " + str(schema.schema_version),
        "    TIMESTAMP_FORMAT = " + _quote(envelope.timestamp_format),
        "    EVENT_NAME_PATTERN = " + _quote(envelope.event_name_pattern),
        "    EVENT_NAME_REGEX = Regexp.new(EVENT_NAME_PATTERN).freeze",
        "    UUID_PATTERN = " + _quote(schema.identifiers.uuid_pattern),
        "    UUID_REGEX = Regexp.new(UUID_PATTERN).freeze",
        "    FREE_FORM_KEY_PATTERN = " + _quote(free_form.key_pattern),
        "    FREE_FORM_KEY_REGEX = Regexp.new(FREE_FORM_KEY_PATTERN).freeze",
        "    NEW_ID_FORMAT = " + _quote(schema.identifiers.new_id_format),
        "    NEW_ID_VERSION = " + _quote(schema.identifiers.new_id_version),
        "    REJECT_UNKNOWN_TOP_LEVEL_FIELDS = " + _literal(envelope.reject_unknown_top_level_fields),
        "    ALLOWED_TOP_LEVEL_FIELDS = " + _frozen_literal(list(envelope.allowed_top_level_fields)),
        "    FREE_FORM_VALUE_TYPES = " + _frozen_literal(list(free_form.value_types)),
        "    VALUES_MUST_BE_REDACTED = " + _literal(free_form.values_must_be_redacted),
        "    UNKNOWN_TOP_LEVEL_FIELD_ACTION = " + _quote(schema.validation.unknown_top_level_field_action),
        "    UNSAFE_FIELD_ACTION = " + _quote(schema.validation.unsafe_field_action),
        "    NULL_VALUES_ALLOWED = " + _literal(schema.validation.null_values_allowed),
        "    REDACTION_CASE_SENSITIVE = " + _literal(redaction.case_sensitive),
        "    REDACTION_KEY_MATCHING = " + _quote(redaction.key_matching),
        "    REDACTION_MISSING_ACTION = " + _quote(redaction.missing_action),
        "    REDACTION_AMBIGUOUS_MATCH_ACTION = " + _quote(redaction.ambiguous_match_action),
        "    REDACTION_FAILURE_ACTION = " + _quote(redaction.redaction_failure_action),
        "    REJECTED_CONTENT_MUST_BE_DISCARDED = " + _literal(redaction.rejected_content_must_be_discarded),
        "",
    ]

    limit_entries = [
        ("MAX_BATCH_EVENTS", limits.max_batch_events),
        ("MAX_EVENT_BYTES", limits.max_event_bytes),
        ("MAX_EVENT_FIELDS", limits.max_event_fields),
        ("MAX_STRING_BYTES", limits.max_string_bytes),
        ("MAX_COLLECTION_ITEMS", limits.max_collection_items),
        ("MAX_FREE_FORM_FIELDS", limits.max_free_form_fields),
        ("MAX_FREE_FORM_VALUE_BYTES", limits.max_free_form_value_bytes),
        ("MAX_DIAGNOSTIC_BUNDLE_EVENTS", contract.diagnostic_bundle.max_events),
        ("MAX_DIAGNOSTIC_BUNDLE_EVENT_BYTES", contract.diagnostic_bundle.max_event_bytes),
        ("MAX_DIAGNOSTIC_BUNDLE_TOTAL_BYTES", contract.diagnostic_bundle.max_total_bytes),
        ("MAX_DIAGNOSTIC_BUNDLE_METADATA_FIELDS", contract.diagnostic_bundle.max_metadata_fields),
        ("MAX_DIAGNOSTIC_BUNDLE_CORRELATION_FIELDS", contract.diagnostic_bundle.max_correlation_fields),
        ("MAX_DIAGNOSTIC_BUNDLE_REDACTION_SUMMARY_ENTRIES", contract.diagnostic_bundle.max_redaction_summary_entries),
    ]
    lines.extend(f"    {name} = {value}" for name, value in limit_entries)
    lines.append("")

    lines.extend(
        f"    {_constant('LEVEL', level)} = {_quote(level)}"
        for level in envelope.canonical_levels
    )
    lines.extend(
        f"    {_constant('FIELD', field.name)} = {_quote(field.name)}"
        for field in fields
    )
    lines.extend(
        f"    {_constant('EVENT', event.name)} = {_quote(event.name)}"
        for event in events
    )
    lines.extend(
        f"    {_constant('SERVICE', service.key)} = {_quote(service.key)}"
        for service in services
    )
    lines.extend(
        f"    {_constant('REJECTION', code)} = {_quote(code)}"
        for code in schema.rejection_codes
    )
    lines.extend(
        f"    {_constant('RETENTION_TIER', tier.name)} = {_quote(tier.name)}"
        for tier in tiers
    )
    lines.extend(
        f"    {_constant('RETENTION_DEFAULT_AGE_SECONDS', tier.name)} = {tier.default_age_seconds}"
        for tier in tiers
    )
    lines.extend([
        f"    FILE_LOGGING_MAX_ACTIVE_SEGMENT_AGE_SECONDS = {contract.file_logging.max_active_segment_age_seconds}",
        f"    FILE_LOGGING_COMPRESSION_ENABLED = {_literal(contract.file_logging.compression_enabled)}",
    ])
    lines.extend([
        "",
        "    CANONICAL_LEVELS = [" + ", ".join(_constant("LEVEL", level) for level in envelope.canonical_levels) + "].freeze",
        "    REQUIRED_FIELDS = [" + ", ".join(_constant("FIELD", name) for name in envelope.required_fields) + "].freeze",
        "    REJECTION_CODES = [" + ", ".join(_constant("REJECTION", code) for code in schema.rejection_codes) + "].freeze",
        "",
        "    FIELD_DEFINITIONS = {",
    ])
    for field in fields:
        definition = {
            "name": field.name,
            "type": field.type,
            "required": field.required,
            "description": field.description,
            "sensitivity": field.sensitivity,
        }
        lines.append(
            f"      {_constant('FIELD', field.name)} => {_literal(definition)}.freeze,"
        )
    lines.extend(["    }.freeze", "", "    SERVICE_DEFINITIONS = {"])
    for service in services:
        lines.append(
            f"      {_constant('SERVICE', service.key)} => {_literal({'key': service.key, 'emitted_name': service.emitted_name})}.freeze,"
        )
    lines.extend(["    }.freeze", "", "    EVENT_DEFINITIONS = {"])
    for event in events:
        definition = {
            "name": event.name,
            "category": event.category,
            "default_level": event.default_level,
            "description": event.description,
            "services": list(sorted(event.services)),
            "trace_required": event.trace_required,
            "audit_eligible": event.audit_eligible,
            "retention_tier": event.retention_tier,
            "bridge_only": event.bridge_only,
        }
        definition_literal = _literal(definition).replace(
            '"services" => [', '"services" => ['
        )
        # Freeze the metadata array as well as its containing definition hash.
        definition_literal = definition_literal.replace(
            '], "trace_required"', '].freeze, "trace_required"'
        )
        lines.append(
            f"      {_constant('EVENT', event.name)} => {definition_literal}.freeze,"
        )
    lines.extend(["    }.freeze", "", "    REDACTION_ACTION_DEFINITIONS = {"])
    for action in sorted(redaction.actions, key=lambda item: item.name):
        lines.append(
            f"      {_quote(action.name)} => {_literal({'name': action.name, 'description': action.description, 'value_preserved': action.value_preserved, 'replacement_used': action.replacement_used, 'replacement_marker': action.replacement_marker})}.freeze,"
        )
    exact_rules = [
        {"category": rule.category, "action": rule.action, "matches": list(sorted(rule.keys))}
        for rule in sorted(redaction.exact_rules, key=lambda item: item.category)
    ]
    fragment_rules = [
        {"category": rule.category, "action": rule.action, "matches": list(sorted(rule.fragments))}
        for rule in sorted(redaction.fragment_rules, key=lambda item: item.category)
    ]
    replacement_marker = next(
        action.replacement_marker
        for action in redaction.actions
        if action.replacement_used and action.replacement_marker is not None
    )
    lines.extend([
        "    }.freeze",
        f"    REDACTION_REPLACEMENT_MARKER = {_quote(replacement_marker)}",
        f"    REDACTION_EXACT_RULES = {_literal(exact_rules)}.freeze",
        f"    REDACTION_FRAGMENT_RULES = {_literal(fragment_rules)}.freeze",
        "",
        "    RETENTION_TIERS = [" + ", ".join(_quote(tier.name) for tier in tiers) + "].freeze",
        "",
        "    module_function",
        "",
        "    def canonical_level?(value)",
        "      CANONICAL_LEVELS.include?(value)",
        "    end",
        "",
        "    def known_field?(value)",
        "      FIELD_DEFINITIONS.key?(value)",
        "    end",
        "",
        "    def known_event?(value)",
        "      EVENT_DEFINITIONS.key?(value)",
        "    end",
        "",
        "    def service_definition(value)",
        "      SERVICE_DEFINITIONS[value]",
        "    end",
        "",
        "    def retention_tier?(value)",
        "      RETENTION_TIERS.include?(value)",
        "    end",
        "",
        "    def field_definition(value)",
        "      FIELD_DEFINITIONS[value]",
        "    end",
        "",
        "    def event_definition(value)",
        "      EVENT_DEFINITIONS[value]",
        "    end",
        "  end",
        "end",
    ])
    return "\n".join(lines).rstrip("\n") + "\n"
